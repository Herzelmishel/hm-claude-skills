@pytest.fixture
def run_script():
    """Factory: run a script via subprocess with HOME pointed at tmp_path.

    Returns (returncode, stdout, stderr).
    """
    def _run(script_path: Path, args: list[str] | None = None,
             *, home: Path | None = None,
             stdin_text: str | None = None) -> tuple[int, str, str]:
        env = os.environ.copy()
        if home is not None:
            env["HOME"] = str(home)
        cmd = [sys.executable, str(script_path)]
        if args:
            cmd.extend(args)
        proc = subprocess.run(
            cmd,
            input=stdin_text,
            capture_output=True,
            text=True,
            env=env,
            check=False,
        )
        return proc.returncode, proc.stdout, proc.stderr
    return _run


