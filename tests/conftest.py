def _replace_yaml_top_level(text: str, key: str, value) -> str:
    """Helper for tests: replace a top-level YAML key. Best-effort.

    Removes any nested/indented child lines belonging to the previous value
    so a list seed can be replaced with a string (or vice versa) cleanly.
    """
    import re

    if value is None:
        replacement = f"{key}: null\n"
    elif isinstance(value, list):
        body = "\n".join(f"  - {item}" for item in value)
        replacement = f"{key}:\n{body}\n"
    elif isinstance(value, str) and "\n" in value:
        body = "\n".join(f"  {line}" for line in value.splitlines())
        replacement = f"{key}: |\n{body}\n"
    elif isinstance(value, str) and value == "":
        replacement = f"{key}: ''\n"
    elif isinstance(value, str):
        replacement = f"{key}: {value}\n"
    else:
        replacement = f"{key}: {value}\n"

    # Match the key line + all subsequent lines that start with whitespace
    # (the indented children of the original mapping/list/block-scalar).
    full_re = re.compile(
        rf"^{re.escape(key)}:[^\n]*\n(?:[ \t]+[^\n]*\n)*",
        re.MULTILINE,
    )
    if full_re.search(text):
        return full_re.sub(replacement, text, count=1)
    return text + ("\n" if not text.endswith("\n") else "") + replacement


